"""FP32 DirectML forward pass for the published dual-input YOLOMG model.

Preprocessing and NMS stay identical to YOLOMGDetector. A static ONNX graph
is cached for each actual letterboxed input shape. The first inference is
profiled to verify actual GPU execution, rather than just provider availability.
"""

from collections import Counter
from hashlib import sha256
import importlib
import json
from pathlib import Path
import tempfile

import numpy as np

from .yolo_detector import YOLOMGDetector


EXPORT_VERSION = "yolomg-dual-fp32-v1-opset13"
DML_PROVIDER = "DmlExecutionProvider"


def _dependencies():
    try:
        onnx = importlib.import_module("onnx")
        ort = importlib.import_module("onnxruntime")
    except ImportError as error:
        raise RuntimeError(
            "DirectML requires onnx and onnxruntime-directml in the selected Python "
            "environment; use the project's .venv-gpu interpreter. No model was downloaded."
        ) from error
    if DML_PROVIDER not in ort.get_available_providers():
        raise RuntimeError(
            "DmlExecutionProvider is unavailable in this Python environment. "
            "Use .venv-gpu/Scripts/python.exe with onnxruntime-directml; CPU fallback is disabled."
        )
    return onnx, ort


def _file_digest(path):
    digest = sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _executed_provider_counts(profile_path):
    with Path(profile_path).open(encoding="utf-8") as stream:
        events = json.load(stream)
    counts = Counter(
        event.get("args", {}).get("provider")
        for event in events
        if event.get("cat") == "Node"
        and event.get("name", "").endswith("_kernel_time")
        and event.get("args", {}).get("provider")
    )
    if not counts.get(DML_PROVIDER, 0):
        raise RuntimeError(
            f"DirectML did not execute any profiled graph nodes (providers: {dict(counts)}). "
            "Refusing a silent CPU-only inference run."
        )
    return dict(counts)


def _vendor_source_digest(repo_dir):
    """Fingerprint all model and utility Python code used during export."""
    root = Path(repo_dir)
    digest = sha256()
    for directory in ('models', 'utils'):
        for path in sorted((root / directory).rglob('*.py')):
            name = path.relative_to(root).as_posix().encode('utf-8')
            digest.update(len(name).to_bytes(4, 'big'))
            digest.update(name)
            digest.update(bytes.fromhex(_file_digest(path)))
    return digest.hexdigest()


class DirectMLYOLOMGDetector(YOLOMGDetector):
    def __init__(
        self, repo_dir, weights, image_size=1280, conf_threshold=0.1,
        threads=4, device_id=0, cache_dir=None,
    ):
        if isinstance(device_id, bool) or not isinstance(device_id, int) or device_id < 0:
            raise ValueError("DirectML device_id must be a nonnegative adapter index")
        self._onnx, self._ort = _dependencies()
        super().__init__(repo_dir, weights, image_size=image_size, device="cpu",
                         conf_threshold=conf_threshold, threads=threads)
        # Concatenating xy/wh avoids ONNX ScatterND generated by indexed writes.
        from models.yolo import Detect
        for module in self.model.modules():
            if isinstance(module, Detect):
                module.inplace = False
        self.device_id = device_id
        self._threads = int(threads)
        self.cache_dir = Path(cache_dir) if cache_dir is not None else (
            Path(__file__).resolve().parents[1] / ".cache" / "onnx"
        )
        self._weight_sha = _file_digest(self.weights)
        self._source_sha = _vendor_source_digest(self.repo_dir)
        self._session = None
        self._session_shape = None
        self.backend_info = {
            "backend": "directml", "device_id": device_id, "precision": "float32",
            "runtime_version": self._ort.__version__, "export_version": EXPORT_VERSION,
            "available_providers": self._ort.get_available_providers(),
            "session_providers": [], "executed_provider_node_counts": {},
            "execution_verified": False,
            "cpu_stages": ["letterbox", "input_conversion", "non_max_suppression", "box_scaling"],
        }

    def _cache_metadata(self, shape):
        return {
            "export_version": EXPORT_VERSION,
            "weights_sha256": self._weight_sha,
            "vendor_source_sha256": self._source_sha,
            "input_shape": json.dumps(list(shape)),
            "precision": "float32",
            "torch_version": str(self._torch.__version__),
            "onnx_version": str(self._onnx.__version__),
        }

    def _onnx_path(self, rgb, motion):
        shape = tuple(int(n) for n in rgb.shape)
        metadata = self._cache_metadata(shape)
        key = sha256(json.dumps(metadata, sort_keys=True).encode()).hexdigest()[:24]
        path = self.cache_dir / f"yolomg_{shape[2]}x{shape[3]}_{key}.onnx"
        if path.is_file():
            cached = self._onnx.load(str(path))
            actual = {item.key: item.value for item in cached.metadata_props}
            if actual != metadata:
                raise RuntimeError(f"ONNX cache metadata mismatch: {path}; remove this cache file and retry")
            return path

        torch = self._torch

        class RawPrediction(torch.nn.Module):
            def __init__(self, model):
                super().__init__()
                self.model = model

            def forward(self, rgb_input, motion_input):
                return self.model(rgb_input, motion_input, augment=False)[0]

        self.cache_dir.mkdir(parents=True, exist_ok=True)
        # Export into a temporary directory, then atomically publish the checked
        # model; interrupted exports cannot leave a seemingly valid cache entry.
        with tempfile.TemporaryDirectory(prefix="yolomg_export_", dir=self.cache_dir) as temp:
            temporary = Path(temp) / "model.onnx"
            torch.onnx.export(
                RawPrediction(self.model).eval(), (rgb, motion), str(temporary),
                input_names=["rgb", "motion"], output_names=["rawprediction"],
                opset_version=13, do_constant_folding=True, dynamo=False,
            )
            graph = self._onnx.load(str(temporary))
            self._onnx.helper.set_model_props(graph, metadata)
            self._onnx.checker.check_model(graph)
            self._onnx.save(graph, str(temporary))
            temporary.replace(path)
        return path

    def _first_run(self, rgb, motion, inputs):
        path = self._onnx_path(rgb, motion)
        self.backend_info["execution_verified"] = False
        with tempfile.TemporaryDirectory(prefix="yolomg_dml_profile_") as temp:
            options = self._ort.SessionOptions()
            options.execution_mode = self._ort.ExecutionMode.ORT_SEQUENTIAL
            options.enable_mem_pattern = False
            options.intra_op_num_threads = self._threads
            options.enable_profiling = True
            options.profile_file_prefix = str(Path(temp) / "profile")
            session = self._ort.InferenceSession(
                str(path), sess_options=options,
                providers=[(DML_PROVIDER, {"device_id": str(self.device_id)}), "CPUExecutionProvider"],
            )
            session.disable_fallback()
            providers = session.get_providers()
            if DML_PROVIDER not in providers:
                session.end_profiling()
                raise RuntimeError(f"DirectML session initialization fell back to {providers}; inference aborted")
            try:
                output = session.run(["rawprediction"], inputs)[0]
            finally:
                profile = session.end_profiling()
            counts = _executed_provider_counts(profile)
        self._session = session
        self._session_shape = tuple(rgb.shape)
        self.backend_info.update({
            "session_providers": providers,
            "executed_provider_node_counts": counts,
            "execution_verified": True,
            "profile_scope": "first inference, optimized graph nodes (fused nodes count once)",
            "cpu_graph_nodes": counts.get("CPUExecutionProvider", 0),
            "input_shape": list(rgb.shape), "onnx_cache": str(path.resolve()),
        })
        return output

    def _predict(self, rgb, motion):
        inputs = {
            "rgb": np.ascontiguousarray(rgb.detach().cpu().numpy(), dtype=np.float32),
            "motion": np.ascontiguousarray(motion.detach().cpu().numpy(), dtype=np.float32),
        }
        if self._session is None or tuple(rgb.shape) != self._session_shape:
            output = self._first_run(rgb, motion, inputs)
        else:
            output = self._session.run(["rawprediction"], inputs)[0]
        if output.dtype != np.float32 or not np.isfinite(output).all():
            raise RuntimeError("DirectML returned invalid/non-FP32 predictions")
        return self._torch.from_numpy(output)
